DROP DATABASE IF EXISTS smart_banking_cms;
CREATE DATABASE smart_banking_cms;
USE smart_banking_cms;

CREATE TABLE Banks (
  bank_id INT PRIMARY KEY,
  bank_name VARCHAR(100) NOT NULL UNIQUE,
  city VARCHAR(60) NOT NULL,
  state VARCHAR(60) NOT NULL
);
CREATE TABLE Customers (
  customer_id INT PRIMARY KEY,
  first_name VARCHAR(50) NOT NULL,
  last_name VARCHAR(50) NOT NULL,
  gender VARCHAR(10) NOT NULL,
  date_of_birth DATE NOT NULL,
  email VARCHAR(120) NOT NULL UNIQUE,
  phone VARCHAR(15) NOT NULL UNIQUE,
  city VARCHAR(60) NOT NULL,
  registration_date DATE NOT NULL
);
CREATE TABLE Accounts (
  account_id INT PRIMARY KEY,
  customer_id INT NOT NULL,
  bank_id INT NOT NULL,
  account_number VARCHAR(30) NOT NULL UNIQUE,
  account_type ENUM('Savings','Current','Salary') NOT NULL,
  balance DECIMAL(14,2) NOT NULL,
  opening_date DATE NOT NULL,
  status ENUM('Active','Inactive') NOT NULL,
  CONSTRAINT fk_accounts_customer FOREIGN KEY (customer_id) REFERENCES Customers(customer_id),
  CONSTRAINT fk_accounts_bank FOREIGN KEY (bank_id) REFERENCES Banks(bank_id)
);
CREATE TABLE Transactions (
  transaction_id INT PRIMARY KEY,
  account_id INT NOT NULL,
  transaction_date DATE NOT NULL,
  transaction_type ENUM('Credit','Debit') NOT NULL,
  amount DECIMAL(14,2) NOT NULL,
  description VARCHAR(150),
  CONSTRAINT fk_transactions_account FOREIGN KEY (account_id) REFERENCES Accounts(account_id)
);
CREATE TABLE Admins (
  admin_id INT PRIMARY KEY,
  admin_name VARCHAR(100) NOT NULL,
  email VARCHAR(120) NOT NULL UNIQUE,
  role VARCHAR(60) NOT NULL
);

